#!/usr/bin/env python3
"""Writes docs/samples/lexer/cpp_source.ol: the text of the lexer functions the "How the lexer works"
example shows and follows line by line, copied VERBATIM from src/lexer.cpp.

The animation highlights the line the lexer is running, so what it shows must be the engine's own
code, not a paraphrase of it. It is generated rather than typed so that it cannot drift by hand, and
tests/check_lexer_source.sh runs this script with --check to catch a lexer.cpp that moved on.

    python3 tools/gen_lexer_source.py            rewrite the file
    python3 tools/gen_lexer_source.py --check    exit 1 when the file is out of date

Ollin strings have no escape for the double quote, and `{` opens an interpolation, so a line is
written with a backtick where the C++ has a double quote (there is no backtick in lexer.cpp) and with
`\\{` where it has a brace. tracer.ol turns the backticks back into quotes when it loads the file.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "src", "lexer.cpp")
TARGET = os.path.join(ROOT, "docs", "samples", "lexer", "cpp_source.ol")

# The functions the animation follows, with the line that opens each of them.
FUNCTIONS = [
    ("skip_whitespace", r"^void Lexer::skip_whitespace\(\) \{$"),
    ("number", r"^Token Lexer::number\(bool leading_dot\) \{$"),
    ("interp_string", r"^void Lexer::interp_string\(std::vector<Token>& out\) \{$"),
    ("identifier", r"^Token Lexer::identifier\(\) \{$"),
    ("comment", r"^void Lexer::comment\(\) \{$"),
    ("block_comment", r"^void Lexer::block_comment\(\) \{$"),
    ("tokenize", r"^std::vector<Token> Lexer::tokenize\(\) \{$"),
]


def encode(line):
    assert "`" not in line, "a backtick in lexer.cpp: the encoding of the quote needs another character"
    return line.replace('"', "`").replace("{", "\\{")


def extract():
    lines = open(SOURCE, encoding="utf-8").read().split("\n")
    out = []
    for name, opening in FUNCTIONS:
        starts = [i for i, l in enumerate(lines) if re.match(opening, l)]
        if len(starts) != 1:
            sys.exit(f"gen_lexer_source: {name}: the line that opens it was found {len(starts)} times")
        first = starts[0]
        last = next(i for i in range(first, len(lines)) if lines[i] == "}")
        out.append((name, first + 1, [l.rstrip() for l in lines[first:last + 1]]))
    return out


def render():
    text = [
        "## GENERATED by tools/gen_lexer_source.py from src/lexer.cpp: do not edit by hand.",
        "## The lexer functions the animation follows, verbatim. `first` is the line of lexer.cpp where each",
        "## one starts. A backtick stands for a double quote, and tracer.ol puts the quotes back.",
        "",
        "const CPP_SOURCE = {",
    ]
    funcs = extract()
    for k, (name, first, lines) in enumerate(funcs):
        text.append(f'    "{name}": {{first: {first}, lines: [')
        for j, l in enumerate(lines):
            comma = "," if j + 1 < len(lines) else ""
            text.append(f'        "{encode(l)}"{comma}')
        text.append("    ]}" + ("," if k + 1 < len(funcs) else ""))
    text.append("}")
    return "\n".join(text) + "\n"


if __name__ == "__main__":
    wanted = render()
    if "--check" in sys.argv:
        have = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if have != wanted:
            print("lexer source: docs/samples/lexer/cpp_source.ol is out of date with src/lexer.cpp")
            print("  run: python3 tools/gen_lexer_source.py")
            sys.exit(1)
        print("OK   lexer source (cpp_source.ol matches src/lexer.cpp)")
    else:
        open(TARGET, "w", encoding="utf-8").write(wanted)
        print("wrote", os.path.relpath(TARGET, ROOT))

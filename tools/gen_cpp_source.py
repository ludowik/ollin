#!/usr/bin/env python3
"""Writes the cpp_source.ol of the examples that follow the engine's own code line by line — "How the
lexer works" (src/lexer.cpp) and "How the parser works" (src/parser.cpp) — copied VERBATIM.

The animation highlights the line the engine is running, so what it shows must be the engine's own
code, not a paraphrase of it. It is generated rather than typed so that it cannot drift by hand, and
tests/check_trace_source.sh runs this script with --check to catch a source file that moved on.

    python3 tools/gen_cpp_source.py                  rewrite every file
    python3 tools/gen_cpp_source.py --check          exit 1 when one is out of date
    python3 tools/gen_cpp_source.py lexer [--check]  only one example

Ollin strings have no escape for the double quote, and `{` opens an interpolation, so a line is
written with a currency sign, \u00a4, where the C++ has a double quote (the sources have none, while
they do use backticks in comments) and with `\\{` where it has a brace. The tracer of each example turns
the signs back into quotes when it loads the file.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# One entry per example: the C++ file, the Ollin file written from it, the table it defines, the class
# whose methods are copied, and those methods. A function is found by the line that opens it, and ends
# at the first line that is a lone `}`.
TARGETS = {
    "lexer": {
        "source": "src/lexer.cpp",
        "target": "docs/samples/lexer/cpp_source.ol",
        "table": "CPP_SOURCE",
        "owner": "Lexer",
        "functions": ["skip_whitespace", "number", "interp_string", "identifier", "comment", "block_comment",
                      "tokenize"],
    },
    "parser": {
        "source": "src/parser.cpp",
        "target": "docs/samples/parser/cpp_source.ol",
        "table": "PARSER_CPP_SOURCE",
        "owner": "Parser",
        "functions": ["parse_body_until", "parse_params", "parse_expr_list", "parse_call_args", "parse",
                      "parse_one_stmt", "finish_assign_from_expr", "decl_stmt", "while_stmt", "do_stmt",
                      "if_stmt", "break_stmt", "continue_stmt", "throw_stmt", "func_decl_stmt",
                      "finish_func_decl", "return_stmt", "multi_assign_stmt", "for_stmt", "expr_stmt", "expr",
                      "binary_level", "comparison", "unary", "power", "parse_postfix", "primary"],
    },
}


QUOTE_MARK = "\u00a4"


def encode(line):
    assert QUOTE_MARK not in line, "the encoding of the quote needs another character"
    return line.replace('"', QUOTE_MARK).replace("{", "\\{")


def extract(name):
    """The functions of one example as [(function, first line number in the C++ file, [its lines])]."""
    spec = TARGETS[name]
    lines = open(os.path.join(ROOT, spec["source"]), encoding="utf-8").read().split("\n")
    out = []
    for fn in spec["functions"]:
        opening = re.compile(rf"^\S.* {spec['owner']}::{fn}\(")
        starts = [i for i, l in enumerate(lines) if opening.match(l)]
        if len(starts) != 1:
            sys.exit(f"gen_cpp_source: {name}: {fn}: the line that opens it was found {len(starts)} times")
        first = starts[0]
        last = next(i for i in range(first, len(lines)) if lines[i] == "}")
        out.append((fn, first + 1, [l.rstrip() for l in lines[first:last + 1]]))
    return out


def render(name):
    spec = TARGETS[name]
    text = [
        f"## GENERATED by tools/gen_cpp_source.py from {spec['source']}: do not edit by hand.",
        f"## The {spec['owner'].lower()} functions the animation follows, verbatim. `first` is the line of "
        f"{os.path.basename(spec['source'])} where each",
        f"## one starts. A {QUOTE_MARK} stands for a double quote, and tracer.ol puts the quotes back.",
        "",
        f"const {spec['table']} = {{",
    ]
    funcs = extract(name)
    for k, (fn, first, lines) in enumerate(funcs):
        text.append(f'    "{fn}": {{first: {first}, lines: [')
        for j, l in enumerate(lines):
            comma = "," if j + 1 < len(lines) else ""
            text.append(f'        "{encode(l)}"{comma}')
        text.append("    ]}" + ("," if k + 1 < len(funcs) else ""))
    text.append("}")
    return "\n".join(text) + "\n"


def main():
    names = [a for a in sys.argv[1:] if not a.startswith("--")] or list(TARGETS)
    stale = False
    for name in names:
        path = os.path.join(ROOT, TARGETS[name]["target"])
        wanted = render(name)
        if "--check" in sys.argv:
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if have != wanted:
                print(f"{name} source: {TARGETS[name]['target']} is out of date with {TARGETS[name]['source']}")
                print("  run: python3 tools/gen_cpp_source.py")
                stale = True
            else:
                print(f"OK   {name} source ({os.path.basename(path)} matches {TARGETS[name]['source']})")
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(wanted)
            print("wrote", TARGETS[name]["target"])
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
